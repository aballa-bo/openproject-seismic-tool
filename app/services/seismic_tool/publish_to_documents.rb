# frozen_string_literal: true

module SeismicTool
  # Copies the analysis images into the project's Documents: for every source
  # document "X" the labelled images go to a document "X_labeled" and the crack
  # masks to "X_masked" (same category as the source). Files are named after the
  # original image: "photo.jpg" -> "photo_labeled.jpg" / "photo_masked.png".
  # Idempotent: images already published (or already attached) are skipped.
  class PublishToDocuments
    Result = Struct.new(:documents, :attached, :errors, keyword_init: true)

    KINDS = {
      "labeled" => { path: :overlay_path, ext: ".jpg", mime: "image/jpeg" },
      "masked" => { path: :mask_path, ext: ".png", mime: "image/png" }
    }.freeze

    def initialize(job:, user:)
      @job = job
      @user = user
      @docs = {}
      @attached = 0
      @errors = []
      @attachment_ids = []
    end

    # Deletes the attachments this job copied into Documents, and the documents the tool
    # created that are left empty. Returns the number of attachments removed.
    def self.remove_published(job)
      ids = Array(job.params["published_attachment_ids"])
      atts = ::Attachment.where(id: ids, container_type: "Document").to_a
      docs = atts.filter_map(&:container).uniq
      atts.each(&:destroy)
      docs.each do |d|
        d.reload
        d.destroy if d.attachments.none? && d.description.to_s.start_with?("Generated by the Seismic tool")
      rescue StandardError => e
        Rails.logger.warn("[seismic_tool] could not clean document #{d&.id}: #{e.message}")
      end
      atts.size
    end

    def call
      results = @job.seismic_image_results.where(status: "done", published_at: nil).includes(attachment: :container)
      results.group_by { |r| r.attachment&.container }.each do |source, group|
        next unless source.is_a?(::Document)

        group.each { |r| publish_result(source, r) }
      end
      remember_documents
      Result.new(documents: @docs.values, attached: @attached, errors: @errors)
    end

    private

    def publish_result(source, result)
      ok = true
      KINDS.each do |kind, spec|
        path = result.public_send(spec[:path])
        next if path.blank? || !File.file?(path)

        filename = "#{File.basename(result.filename, '.*')}_#{kind}#{spec[:ext]}"
        doc = target_document(source, kind)
        next if doc.attachments.exists?(filename: filename)

        attach(doc, path, filename, spec[:mime])
        @attached += 1
      rescue StandardError => e
        ok = false
        @errors << "#{result.filename} (#{kind}): #{e.message}"
        Rails.logger.warn("[seismic_tool] publish failed for result #{result.id}: #{e.class}: #{e.message}")
      end
      result.update_columns(published_at: Time.current) if ok
    end

    def target_document(source, kind)
      @docs[[source.id, kind]] ||= begin
        title = "#{source.title}_#{kind}"
        ::Document.find_by(project_id: source.project_id, title: title) ||
          ::Document.create!(project: source.project, title: title, **document_kind_attributes(source),
                             description: "Generated by the Seismic tool (analysis ##{@job.id}) from the document " \
                                          "\"#{source.title}\".")
      end
    end

    # OpenProject <= 16: documents have a category (DocumentCategory enumeration);
    # >= 17: a DocumentType (`type`). Keep whichever the source document uses.
    def document_kind_attributes(source)
      if ::Document.reflect_on_association(:category)
        { category: source.category }
      elsif ::Document.reflect_on_association(:type)
        { type: source.type }
      else
        {}
      end
    end

    def attach(doc, path, filename, mime)
      File.open(path, "rb") do |f|
        upload = ActionDispatch::Http::UploadedFile.new(tempfile: f, filename: filename, type: mime)
        desc = "Seismic tool, analysis ##{@job.id}"
        if defined?(::Attachments::CreateService) && ::Attachments::CreateService.respond_to?(:bypass_whitelist)
          call = ::Attachments::CreateService.bypass_whitelist(user: @user)
                                             .call(container: doc, file: upload, filename: filename, description: desc)
          raise call.errors.full_messages.join(", ") unless call.success?

          @attachment_ids << call.result.id if call.result.respond_to?(:id)
        else
          att = ::Attachment.new(container: doc, author: @user, file: upload, description: desc)
          att.save!
          @attachment_ids << att.id
        end
      end
    end

    def remember_documents
      ids = (Array(@job.params["published_document_ids"]) + @docs.values.map(&:id)).uniq
      att_ids = (Array(@job.params["published_attachment_ids"]) + @attachment_ids).uniq
      return if ids.empty?

      @job.update_columns(params: @job.params.merge("published_document_ids" => ids,
                                                   "published_attachment_ids" => att_ids))
    end
  end
end
